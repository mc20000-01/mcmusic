export const FALLBACK_ICON = "circle-help";

const SVG_NS = "http://www.w3.org/2000/svg";

export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}

/**
 * Build an SVG icon element.
 * Unknown or missing names render the fallback icon — never an empty box.
 */
export function icon(name, opts = {}) {
  const {
    size = 18, cls = "", stroke = 1.8, title = "", filled = false, opacity = null,
  } = opts;

  const key = hasIcon(name) ? name : FALLBACK_ICON;
  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", filled ? "currentColor" : "none");
  svg.setAttribute("stroke", filled ? "none" : "currentColor");
  svg.setAttribute("stroke-width", String(stroke));
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", title ? "false" : "true");
  svg.setAttribute("focusable", "false");
  if (cls) svg.setAttribute("class", cls);
  if (opacity != null) svg.setAttribute("opacity", String(opacity));
  if (title) {
    const t = document.createElementNS(SVG_NS, "title");
    t.textContent = title;
    svg.appendChild(t);
  }
  svg.innerHTML = PATHS[key];
  svg.dataset.icon = key;
  return svg;
}

export function iconHTML(name, opts = {}) {
  return icon(name, opts).outerHTML;
}

/** Swap the glyph inside an existing button without leaking listeners. */
export function setIcon(el, name, opts = {}) {
  if (!el) return null;
  const next = icon(name, opts);
  el.replaceChildren(next);
  return next;
}

/** The repeat control has three states; this keeps name/opacity logic in one place. */
export function repeatIcon(state) {
  const name = state === "one" ? "repeat-1" : "repeat";
  return icon(name, { size: 17, opacity: state === "off" ? 0.45 : 1,
                      title: `Repeat: ${state}` });
}

export function volumeIcon(muted, level) {
  if (muted) return icon("volume-x", { size: 17, title: "Muted" });
  if (level <= 0.01) return icon("volume-x", { size: 17, title: "Volume 0" });
  if (level < 0.5) return icon("volume-1", { size: 17, title: "Volume low" });
  return icon("volume-2", { size: 17, title: "Volume" });
}

